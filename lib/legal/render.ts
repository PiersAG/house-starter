// Every legal document in one list, and their markdown form for docs/legal/
// (`npm run legal:render` writes it; tests/unit/legal-documents.test.ts fails
// when the committed files differ, so the reviewed file is always what the page
// shows). While the business details are unfilled or the review is not
// recorded (config/legal.ts), each file starts with the launch gate's stub
// marker, so the gate (app-business-core agents/gtm/live_open_gate.py) refuses
// an app whose documents are still the template.

import { REVIEW_NOTE, legalDetails, unfilledDetails, type LegalDetails } from "@/config/legal";
import { customerDpa, serviceAgreement, termsOfService } from "@/lib/legal/contracts";
import { privacyPolicy, retentionPolicy, subprocessorList } from "@/lib/legal/privacy-policy";
import type { LegalDocument } from "@/lib/legal/types";

/** The launch gate's stub sentinel (agents/gtm/live_open_gate.py STUB_MARKER). */
export const STUB_MARKER = "STUB — replace before requesting LIVE-OPEN";

export function legalDocuments(d: LegalDetails = legalDetails): LegalDocument[] {
  return [
    privacyPolicy(d),
    termsOfService(d),
    subprocessorList(d),
    customerDpa(d),
    serviceAgreement(d),
    retentionPolicy(d),
  ];
}

/** True when the documents are still the template: details unfilled or not reviewed. */
export function isDraft(d: LegalDetails = legalDetails): boolean {
  return unfilledDetails(d).length > 0 || d.review === null;
}

/** The document as markdown, as written to docs/legal/<file>. */
export function toMarkdown(doc: LegalDocument, d: LegalDetails = legalDetails): string {
  const out: string[] = [];
  if (isDraft(d)) {
    out.push(STUB_MARKER, "");
    const missing = unfilledDetails(d);
    out.push(
      `Generated by \`npm run legal:render\` from config/legal.ts, config/personal-data.ts and config/subprocessors.ts. Do not edit by hand.${missing.length ? ` Still to fill in config/legal.ts: ${missing.join(", ")}.` : ""}${d.review ? "" : " The review is not recorded yet."}`,
      "",
    );
  }
  out.push(`# ${doc.title}`, "");
  out.push(d.review ? `Reviewed by ${d.review.reviewedBy} on ${d.review.reviewedOn}.` : `> ${REVIEW_NOTE}`, "");
  out.push(doc.summary, "");
  for (const s of doc.sections) {
    out.push(`## ${s.heading}`, "");
    for (const p of s.paragraphs ?? []) out.push(p, "");
    if (s.bullets?.length) {
      for (const b of s.bullets) out.push(`- ${b}`);
      out.push("");
    }
  }
  return out.join("\n").replace(/\n+$/, "\n");
}
