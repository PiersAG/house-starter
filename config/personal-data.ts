// The personal-data map (app-business-core issue 745; Matt Murphy #203: "if you
// cannot list every piece of personal data in your application touches your
// privacy policy is fiction audit the data map where it goes").
//
// One entry per table in lib/schema.ts, plus every place outside the database
// that personal data reaches. Each entry says, in plain words, what the data
// is, why the app holds it, on what lawful basis, which outside services it
// goes to, how long it is kept and what happens to it when the account is
// erased. Three things read it, so they cannot disagree with each other:
//   * the privacy policy and the retention policy (lib/legal/documents.ts);
//   * the data report a user downloads (lib/privacy/data-report.ts);
//   * the deletion pipeline (lib/privacy/deletion.ts), which erases each table
//     the way its entry says.
//
// tests/unit/personal-data-map.test.ts fails when a table in lib/schema.ts is
// missing here, when a column named here does not exist, when a column that
// can identify a person (an id, an email, an IP address, a name, free text) is
// not listed as personal or explained, or when a service named here is not on
// config/subprocessors.ts. A builder adding a table adds its entry in the same
// change.

