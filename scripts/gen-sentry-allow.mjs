#!/usr/bin/env node
// Writes lib/observability/sentry-allow.generated.ts: every setting name
// declared in .env.contract, the only setting names a quoted value in an error
// message may keep on its way to Sentry (lib/observability/sentry-scrub.ts,
// PiersAG/app-business-core#761, Dispatch AT review 2). Names only, never a
// value. tests/unit/sentry-allow.test.ts fails when the file and .env.contract
// disagree; rerun this after adding a line to .env.contract.
//
// Usage: node scripts/gen-sentry-allow.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/** The names declared in .env.contract text, sorted, each once. */
export function contractNames(text) {
  const names = text
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#") && l.includes("="))
    .map((l) => l.slice(0, l.indexOf("=")).trim())
    .filter((n) => /^[A-Z][A-Z0-9_]*$/.test(n));
  return [...new Set(names)].sort();
}

export function render(names) {
  return [
    "// Generated by scripts/gen-sentry-allow.mjs from .env.contract. Do not edit:",
    "// rerun the script. tests/unit/sentry-allow.test.ts fails when this drifts.",
    "",
    "export const ENV_CONTRACT_NAMES: readonly string[] = [",
    ...names.map((n) => `  "${n}",`),
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const names = contractNames(readFileSync(join(ROOT, ".env.contract"), "utf8"));
  writeFileSync(join(ROOT, "lib/observability/sentry-allow.generated.ts"), render(names));
  console.log(`wrote ${names.length} names`);
}
